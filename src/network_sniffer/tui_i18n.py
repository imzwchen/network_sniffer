import re
from dataclasses import dataclass


@dataclass(slots=True)
class Language:
    code: str

    def toggle(self) -> None:
        self.code = "zh" if self.code == "en" else "en"

    def __call__(self, message: str, **values: object) -> str:
        text = _CHINESE.get(message, message) if self.code == "zh" else message
        return text.format(**values) if values else text

    def detail(self, message: str) -> str:
        text = self(message)
        if self.code == "zh" and text == message:
            for pattern, translation in _DETAILS:
                match = pattern.fullmatch(message)
                if match:
                    return translation.format(*match.groups())
        return text


